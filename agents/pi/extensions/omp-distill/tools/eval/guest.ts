/**
 * Guest-side REPL program for the eval tool.
 *
 * This source is embedded as a string and spawned INSIDE the secure-exec VM.
 * It provides omp-style persistent cells: state set on `globalThis` (or via
 * `var`/`function` declarations) survives across cells and across tool calls.
 *
 * Protocol (NDJSON frames over stdin/stdout):
 *   host -> guest: {"t":"cell", id, code} | {"t":"bridge_result", id, ok, result?, error?}
 *   guest -> host: frames prefixed with "\u0000omp1:" on stdout:
 *     ready | out | err | display | bridge | cell_end
 *
 * Cell output (console.log etc.) travels as `out`/`err` frames; user code
 * printing the raw prefix would corrupt the protocol — acceptable in practice.
 */

export const GUEST_REPL_SOURCE = [
  'import { createInterface } from "node:readline";',
  'import { readFile, writeFile } from "node:fs/promises";',
  "",
  'const P = "\\u0000omp1:";',
  "const send = (frame) => process.stdout.write(P + JSON.stringify(frame) + \"\\n\");",
  "const log = (s) => send({ t: \"out\", s });",
  "const err = (s) => send({ t: \"err\", s });",
  "",
  "// ---- console interception (cell output) ----",
  "const fmt = (a) => a.map((x) => typeof x === \"string\" ? x : safeStringify(x)).join(\" \");",
  "function safeStringify(x) {",
  "  try {",
  "    const s = JSON.stringify(x);",
  "    return s === undefined ? String(x) : s;",
  "  } catch { return String(x); }",
  "}",
  'console.log = (...a) => log(fmt(a));',
  'console.info = (...a) => log(fmt(a));',
  'console.warn = (...a) => log(fmt(a));',
  'console.error = (...a) => err(fmt(a));',
  "",
  "// ---- tool bridge ----",
  "let bridgeSeq = 0;",
  "const bridgePending = new Map();",
  "async function bridgeCall(name, args) {",
  "  const id = \"b\" + (++bridgeSeq);",
  "  send({ t: \"bridge\", id, name, args: args ?? {} });",
  "  return new Promise((resolve, reject) => {",
  "    bridgePending.set(id, { resolve, reject });",
  "  });",
  "}",
  "function handleBridgeResult(frame) {",
  "  const p = bridgePending.get(frame.id);",
  "  if (!p) return;",
  "  bridgePending.delete(frame.id);",
  "  if (frame.ok) p.resolve(frame.result);",
  "  else p.reject(new Error(frame.error ?? \"tool call failed\"));",
  "}",
  "const tool = new Proxy({}, {",
  "  get: (_t, name) => (args) => bridgeCall(String(name), args),",
  "});",
  "",
  "// ---- helpers ----",
  "async function readHelper(path, opts = {}) {",
  '  if (typeof path !== "string") throw new Error("read(path) expects a string path");',
  '  if (/^(https?|file|skill|pi|issue|pr|conflict|vault):\\/\\//.test(path)) {',
  "    const r = await bridgeCall(\"read\", Object.assign({ path }, opts));",
  '    return typeof r === "string" ? r : JSON.stringify(r);',
  "  }",
  '  const text = await readFile(path, "utf8");',
  "  if (!opts.offset && !opts.limit) return text;",
  '  const lines = text.split("\\n");',
  "  const start = (opts.offset ?? 1) - 1;",
  "  const end = opts.limit ? start + opts.limit : undefined;",
  '  return lines.slice(Math.max(0, start), end).join("\\n");',
  "}",
  "",
  "async function writeHelper(path, content) {",
  '  if (typeof path !== "string") throw new Error("write(path, content) expects a string path");',
  '  if (/^(https?|file|skill|pi|issue|pr|conflict|vault):\\/\\//.test(path)) {',
  '    throw new Error("write() does not support protocol paths: " + path);',
  "  }",
  '  await writeFile(path, String(content), "utf8");',
  "  return true;",
  "}",
  "",
  "function envHelper(name) {",
  "  // env is denied inside the VM; ask the host for an allowlisted view",
  '  return bridgeCall("__env", name !== undefined ? { name } : {});',
  "}",
  "",
  "// ---- cell evaluation ----",
  "function wrapCode(code) {",
  "  const needsWrap = /\\bawait\\b/.test(code) || /(^|[;\\n])\\s*return\\b/m.test(code);",
  '  return needsWrap ? "(async () => {\\n" + code + "\\n})()" : code;',
  "}",
  "",
  "async function evalCell(id, code) {",
  "  const hasReturn = /(^|[;\\n])\\s*return\\b/m.test(code);",
  "  try {",
  "    const result = await (0, eval)(wrapCode(code));",
  "    if (hasReturn && result !== undefined) send({ t: \"display\", v: result });",
  '    send({ t: "cell_end", id, ok: true });',
  "  } catch (e) {",
  '    const message = e instanceof Error ? e.name + ": " + e.message : String(e);',
  '    send({ t: "cell_end", id, ok: false, error: message });',
  "  }",
  "}",
  "",
  "// ---- prelude install ----",
  "Object.assign(globalThis, {",
  "  tool,",
  '  display: (v) => send({ t: "display", v }),',
  "  read: readHelper,",
  "  write: writeHelper,",
  "  env: envHelper,",
  "});",
  "",
  "// ---- main loop ----",
  'const rl = createInterface({ input: process.stdin, terminal: false });',
  'rl.on("line", (line) => {',
  "  let frame;",
  "  try { frame = JSON.parse(line); } catch { return; }",
  '  if (frame.t === "cell") evalCell(frame.id, frame.code).catch(() => {});',
  '  else if (frame.t === "bridge_result") handleBridgeResult(frame);',
  "});",
  'rl.on("close", () => process.exit(0));',
  "",
  'send({ t: "ready" });',
].join("\n");
